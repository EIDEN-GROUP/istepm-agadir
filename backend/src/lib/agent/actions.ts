export function getToolDefinitions() {
  return ACTIONS.map((a) => ({
    type: "function" as const,
    function: {
      name: a.name,
      description: `${a.description}\nMéthode: ${a.method} ${a.path}\nCatégorie: ${a.category}`,
      parameters: {
        type: "object",
        properties: Object.fromEntries(
          a.params.map((p) => [
            p.name,
            {
              type: p.type === "array" ? "array" : p.type === "object" ? "object" : p.type,
              description: p.description + (p.enum ? ` (valeurs possibles: ${p.enum.join(", ")})` : ""),
              ...(p.enum ? { enum: p.enum } : {}),
              ...(p.type === "array" ? { items: { type: "object" } } : {}),
            },
          ]),
        ),
        required: a.params.filter((p) => p.required).map((p) => p.name),
      },
    },
    _meta: {
      method: a.method,
      path: a.path,
      category: a.category,
      requiredRoles: a.requiredRoles,
    },
  }));
}
